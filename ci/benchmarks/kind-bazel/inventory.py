#!/usr/bin/env python3
"""Project the discovered public smoke inventory into individual Bazel targets."""

import argparse
import json
import sys
from pathlib import Path


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--source", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    sys.path.insert(0, str(args.source.resolve()))
    from space_smoke.scenarios import REGISTRY

    selected = REGISTRY.select(backend="kind")
    pairs = sorted(
        (surface, scenario.id)
        for scenario in selected
        for surface in scenario.api_surfaces
        if scenario.telemetry_mode in (None, "otel")
    )
    held = sorted(
        (scenario.id, scenario.quarantined or scenario.ignored)
        for scenario in REGISTRY
        if scenario.quarantined is not None or scenario.ignored is not None
    )
    text = '"""Generated by inventory.py from the public scenario registry."""\n\n'
    text += "KIND_SCENARIOS = [\n"
    text += "".join(
        f"    ({json.dumps(surface)}, {json.dumps(name)}),\n" for surface, name in pairs
    )
    text += (
        "]\n\nWITHHELD_SCENARIOS = ["
        + ", ".join(
            f"({json.dumps(name)}, {json.dumps(reason)})" for name, reason in held
        )
        + "]\n"
    )
    if args.check:
        if not args.output.exists() or args.output.read_text() != text:
            raise SystemExit("Smoke targets are stale; regenerate with inventory.py")
    else:
        args.output.write_text(text)
    print(
        f"{len(pairs)} scenario/surface targets; {len(held)} explicitly withheld scenarios"
    )


if __name__ == "__main__":
    main()
